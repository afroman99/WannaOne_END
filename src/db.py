"""공용 DB (Supabase Postgres): 설비관리자 노트북과 작업자 폰이 같은 작업·기록을 본다 (2차 업그레이드 2026-10-16).

    from src import db
    pg = db.Postgres(url)          # Secrets [db] url (Supabase → Connect → Session pooler 주소)
    with pg.conn() as c:           # 연결 풀에서 하나 빌려 쓰고, 끝나면 커밋(오류면 되돌림)하고 돌려준다
        c.execute('SELECT ... WHERE id=?', [1])      # 자리표시는 SQLite와 같은 ? 로 쓴다 (안에서 %s로 바꾼다)

보안
  - 표는 별도 스키마 castpdm에 둔다. Supabase가 공개 API(PostgREST)로 내보내는 것은 public 스키마뿐이다
  - 그래도 RLS를 켜 둔다(정책 없음 = 공개 API 키로는 아무것도 못 읽음). 앱은 DB 주인 계정으로 접속해 RLS의 영향을 받지 않는다
  - 접속 주소(비밀번호 포함)는 Secrets에만 둔다. 화면·로그에 쓰지 않는다
  - 값은 항상 자리표시(파라미터)로 넘긴다. SQL 문자열에 값을 이어 붙이지 않는다

psycopg는 공용 DB를 쓸 때만 불러온다 (로컬 SQLite만 쓰면 설치하지 않아도 된다).
"""

import contextlib

SCHEMA = 'castpdm'

DDL = [
    f'CREATE SCHEMA IF NOT EXISTS {SCHEMA}',
    f"""CREATE TABLE IF NOT EXISTS {SCHEMA}.tasks(
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, split TEXT NOT NULL, sid TEXT NOT NULL, title TEXT NOT NULL,
        team TEXT NOT NULL, priority TEXT NOT NULL, due_h DOUBLE PRECISION NOT NULL, created_h DOUBLE PRECISION NOT NULL,
        started_h DOUBLE PRECISION, completed_h DOUBLE PRECISION, guide TEXT NOT NULL, reason TEXT NOT NULL, option TEXT NOT NULL,
        outcome TEXT NOT NULL DEFAULT '', details TEXT NOT NULL DEFAULT '', judged TEXT NOT NULL DEFAULT '',
        confirmed TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
        completed_at TEXT NOT NULL DEFAULT '')""",
    f"""CREATE TABLE IF NOT EXISTS {SCHEMA}.action_log(
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, recorded_at TEXT NOT NULL, split TEXT NOT NULL,
        sid TEXT NOT NULL, hour DOUBLE PRECISION NOT NULL, kind TEXT NOT NULL, who TEXT NOT NULL, option TEXT NOT NULL,
        part TEXT NOT NULL, judged TEXT NOT NULL, confirmed TEXT NOT NULL, note TEXT NOT NULL)""",
    f"""CREATE TABLE IF NOT EXISTS {SCHEMA}.settings(
        key TEXT PRIMARY KEY, value TEXT NOT NULL, updated_at TEXT NOT NULL)""",
    *[f'ALTER TABLE {SCHEMA}.{t} ENABLE ROW LEVEL SECURITY' for t in ('tasks', 'action_log', 'settings')],
    # 2026-10-21에 덧붙인 칸 (작업 중단·실제 조치). 이미 있으면 건너뛴다. 기존 기록은 지우거나 바꾸지 않는다
    f'ALTER TABLE {SCHEMA}.tasks ADD COLUMN IF NOT EXISTS stopped_h DOUBLE PRECISION',
    *[f"ALTER TABLE {SCHEMA}.tasks ADD COLUMN IF NOT EXISTS {c} TEXT NOT NULL DEFAULT ''" for c in ('stop_why', 'action', 'action_why', 'members', 'leader', 'checks')],
    # 인원 부재 (2026-10-21): 설비관리자가 인원 현황에서 사람마다 종류·기간을 고른다
    f"""CREATE TABLE IF NOT EXISTS {SCHEMA}.absences(
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, team TEXT NOT NULL, kind TEXT NOT NULL,
        start_h DOUBLE PRECISION NOT NULL, end_h DOUBLE PRECISION NOT NULL, note TEXT NOT NULL DEFAULT '', updated_at TEXT NOT NULL)""",
    f'ALTER TABLE {SCHEMA}.absences ENABLE ROW LEVEL SECURITY',
]


class _Conn:
    """SQLite처럼 쓰는 얇은 감싸개: execute(sql, params)에서 ? → %s"""

    def __init__(self, conn):
        self.raw = conn

    def execute(self, sql, params=()):
        return self.raw.execute(sql.replace('?', '%s'), list(params))


class Postgres:
    kind = 'postgres'

    def __init__(self, url, min_size=1, max_size=4):
        import psycopg
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool
        # prepare_threshold=None: Supabase 연결 풀러(transaction 모드)에서도 되도록 준비된 문장을 쓰지 않는다
        self.pool = ConnectionPool(url, min_size=min_size, max_size=max_size, open=True, timeout=15,
                                   check=ConnectionPool.check_connection,
                                   kwargs={'row_factory': dict_row, 'prepare_threshold': None, 'connect_timeout': 10})
        self.errors = (psycopg.Error,)
        with self.conn() as c:
            for sql in DDL:
                c.execute(sql)

    @contextlib.contextmanager
    def conn(self):
        with self.pool.connection() as conn:       # 블록이 끝나면 커밋, 오류면 롤백
            yield _Conn(conn)

    def close(self):
        self.pool.close()
